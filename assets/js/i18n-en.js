/* Traducción al inglés de las páginas públicas. La clave es el texto exacto en español
   (espacios juntados), el valor es el inglés. Al cambiar un texto en el HTML, cambiar aquí la
   clave también o quedará en español. Los textos con números o nombres van en `patterns`. */
// '18 de diciembre de 2026' -> 'December 18, 2026' (fechas que pintan los scripts).
window.XH_EN_DATE = function (text) {
  var months = { enero: 'January', febrero: 'February', marzo: 'March', abril: 'April', mayo: 'May', junio: 'June', julio: 'July', agosto: 'August', septiembre: 'September', setiembre: 'September', octubre: 'October', noviembre: 'November', diciembre: 'December' };
  var m = String(text).match(/^(\d{1,2}) de (\S+) de (\d{4})$/);
  return m && months[m[2].toLowerCase()] ? months[m[2].toLowerCase()] + ' ' + m[1] + ', ' + m[3] : text;
};
